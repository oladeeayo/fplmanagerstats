#!/usr/bin/env node
// scripts/generate-player-positions.mjs
// Fetches FPL bootstrap data and generates src/playerPositions.js
// Run: node scripts/generate-player-positions.mjs

import https from 'https';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(__dirname, '../src/playerPositions.js');

function fetch(url) {
  return new Promise((resolve, reject) => {
    https.get(url, { headers: { 'User-Agent': 'Mozilla/5.0' } }, (res) => {
      let data = '';
      res.on('data', (chunk) => data += chunk);
      res.on('end', () => resolve(JSON.parse(data)));
      res.on('error', reject);
    }).on('error', reject);
  });
}

const POSITION_MAP = { 1: 'GK', 2: 'DEF', 3: 'MID', 4: 'FWD' };

// Detailed positional mapping: element_type + playing history -> granular position
// DEF -> LB/CB/RB, MID -> LW/CAM/CM/CDM/RW, FWD -> CF/ST
const ZONE_MAP = {
  // mapped from FPL's list_position attribute (available via element-summary)
  'Right Wing': 'RW', 'Left Wing': 'LW', 'Attacking Midfield': 'CAM',
  'Central Midfield': 'CM', 'Defensive Midfield': 'CDM',
  'Right Back': 'RB', 'Left Back': 'LB', 'Centre Back': 'CB',
  'Center Forward': 'CF', 'Striker': 'ST',
};

async function main() {
  console.log('Fetching FPL bootstrap data...');
  const bootstrap = await fetch('https://fantasy.premierleague.com/api/bootstrap-static/');
  const players = bootstrap.elements;
  const teams = Object.fromEntries(bootstrap.teams.map(t => [t.id, t.short_name]));

  const positions = {};
  let processed = 0;

  // Process in batches of 50 to avoid hammering the API
  const BATCH = 50;
  for (let i = 0; i < players.length; i += BATCH) {
    const batch = players.slice(i, i + BATCH);
    const results = await Promise.all(
      batch.map(async (player) => {
        try {
          const summary = await fetch(`https://fantasy.premierleague.com/api/element-summary/${player.id}/`);
          const history = summary.history || [];
          const lastSeason = history.filter(h => h.season === '202425');
          if (lastSeason.length === 0) return { web_name: player.web_name, zone: null };

          // Count minutes in each zone from the last 10 appearances
          const recent = lastSeason.slice(-10);
          const zoneCounts = {};
          for (const match of recent) {
            const zone = match.player_position;
            if (zone) zoneCounts[zone] = (zoneCounts[zone] || 0) + 1;
          }
          const dominantZone = Object.entries(zoneCounts).sort((a, b) => b[1] - a[1])[0]?.[0];
          return { web_name: player.web_name, zone: dominantZone };
        } catch {
          return { web_name: player.web_name, zone: null };
        }
      })
    );

    for (const r of results) {
      const detailed = r.zone ? (ZONE_MAP[r.zone] || POSITION_MAP[players.find(p => p.web_name === r.web_name)?.element_type]) : null;
      if (detailed) {
        positions[r.web_name] = detailed;
      }
    }
    processed += batch.length;
    process.stdout.write(`\rProcessed ${processed}/${players.length} players...`);
  }

  console.log('\n');

  // Group by team for the output file
  const playersByTeam = {};
  for (const player of players) {
    const team = teams[player.team];
    if (!playersByTeam[team]) playersByTeam[team] = [];
    playersByTeam[team].push({ web_name: player.web_name, zone: positions[player.web_name] });
  }

  let output = `// AUTO-GENERATED by scripts/generate-player-positions.mjs — DO NOT EDIT\n`;
  output += `// Generated: ${new Date().toISOString()}\n`;
  output += `const DETAILED_POSITIONS = {\n`;

  const teamOrder = [...new Set(players.map(p => teams[p.team]))].sort();
  for (const team of teamOrder) {
    const teamPlayers = playersByTeam[team].filter(p => p.zone);
    if (teamPlayers.length === 0) continue;
    output += `  // ${team}\n`;
    for (const p of teamPlayers.sort((a, b) => a.web_name.localeCompare(b.web_name))) {
      output += `  "${p.web_name}": "${p.zone}",\n`;
    }
  }

  output += `};\n\n`;
  output += `module.exports = { DETAILED_POSITIONS };\n`;

  fs.writeFileSync(OUT, output, 'utf-8');
  console.log(`Written ${Object.keys(positions).length} positions to ${OUT}`);
}

main().catch(console.error);
